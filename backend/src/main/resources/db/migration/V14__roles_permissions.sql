-- Roles move from a fixed list (ADMIN / MANAGER / CASHIER) to the database: built-in roles plus
-- roles admins create, each a set of permissions (the permission list itself is fixed in code).
-- Existing admins become Super Admins, so nobody loses access; managers and cashiers keep theirs.
CREATE TABLE roles (
    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL UNIQUE,
    name        VARCHAR(60)  NOT NULL UNIQUE,
    description VARCHAR(255) NULL,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Every permission, including future ones; can't be edited.
    super_admin BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at  TIMESTAMP(6) NULL,
    updated_by  BIGINT       NULL,
    CONSTRAINT fk_role_updated_by FOREIGN KEY (updated_by) REFERENCES users (id)
);

CREATE TABLE role_permissions (
    role_id    BIGINT      NOT NULL,
    permission VARCHAR(40) NOT NULL,
    PRIMARY KEY (role_id, permission),
    CONSTRAINT fk_role_permission_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE
);

