package com.pos.audit;

/** What happened. Each action belongs to a category the audit log can be filtered by. */
public enum AuditAction {
    LOGIN(Category.AUTH), LOGIN_FAILED(Category.AUTH), ACCOUNT_LOCKED(Category.AUTH), LOGOUT(Category.AUTH),
    PASSWORD_CHANGED(Category.AUTH), SESSION_REUSE_DETECTED(Category.AUTH),

    USER_CREATED(Category.USERS), USER_UPDATED(Category.USERS), USER_PASSWORD_RESET(Category.USERS),
    USER_UNLOCKED(Category.USERS), USER_SESSIONS_REVOKED(Category.USERS), SESSION_ENDED(Category.USERS),
    PROFILE_PHOTO_CHANGED(Category.USERS),
    ROLE_CREATED(Category.USERS), ROLE_UPDATED(Category.USERS), ROLE_DELETED(Category.USERS),

    SETTINGS_UPDATED(Category.SETTINGS), LOGO_CHANGED(Category.SETTINGS),
    TAX_RATE_CREATED(Category.SETTINGS), TAX_RATE_UPDATED(Category.SETTINGS),
    CURRENCY_CREATED(Category.SETTINGS), CURRENCY_UPDATED(Category.SETTINGS), EXCHANGE_RATE_SET(Category.SETTINGS),
    BRANCH_CREATED(Category.SETTINGS), BRANCH_UPDATED(Category.SETTINGS),
    STORAGE_CREATED(Category.SETTINGS), STORAGE_UPDATED(Category.SETTINGS),
    UNIT_CREATED(Category.SETTINGS), UNIT_UPDATED(Category.SETTINGS), UNIT_DELETED(Category.SETTINGS),
    CATEGORY_CREATED(Category.SETTINGS), CATEGORY_UPDATED(Category.SETTINGS), CATEGORY_DELETED(Category.SETTINGS),

    OFFERING_CREATED(Category.CATALOG), OFFERING_UPDATED(Category.CATALOG),

    STOCK_CHANGED(Category.INVENTORY), STOCK_ADJUSTED(Category.INVENTORY), STOCK_COUNTED(Category.INVENTORY), TRANSFER_CREATED(Category.INVENTORY), TRANSFER_RECEIVED(Category.INVENTORY),
    TRANSFER_CANCELLED(Category.INVENTORY),

    ORDER_CANCELLED(Category.SALES), ORDER_REFUNDED(Category.SALES), ORDER_RETURNED(Category.SALES),
    PRICE_OVERRIDDEN(Category.SALES), ITEM_DISCOUNTED(Category.SALES),
    SALE_HELD(Category.SALES), HELD_SALE_RESUMED(Category.SALES), HELD_SALE_VOIDED(Category.SALES), HELD_SALE_EXPIRED(Category.SALES),

    CUSTOMER_CREATED(Category.SALES), CUSTOMER_UPDATED(Category.SALES),

    VENDOR_CREATED(Category.PURCHASING), VENDOR_UPDATED(Category.PURCHASING),
    PO_CREATED(Category.PURCHASING), PO_UPDATED(Category.PURCHASING), PO_ORDERED(Category.PURCHASING),
    PO_CANCELLED(Category.PURCHASING), PO_CLOSED(Category.PURCHASING), GOODS_RECEIVED(Category.PURCHASING),
    VENDOR_INVOICE_RECORDED(Category.PURCHASING), VENDOR_INVOICE_VOIDED(Category.PURCHASING),
    VENDOR_PAYMENT_RECORDED(Category.PURCHASING),

    PROMOTION_CREATED(Category.MARKETING), PROMOTION_UPDATED(Category.MARKETING), PROMOTION_DELETED(Category.MARKETING),
    COUPONS_CREATED(Category.MARKETING), COUPON_UPDATED(Category.MARKETING),
    LOYALTY_SETTINGS_UPDATED(Category.MARKETING), POINTS_ADJUSTED(Category.MARKETING),
    SEGMENT_CREATED(Category.MARKETING), SEGMENT_UPDATED(Category.MARKETING), SEGMENT_DELETED(Category.MARKETING),
    CAMPAIGN_CREATED(Category.MARKETING), CAMPAIGN_PREPARED(Category.MARKETING), CAMPAIGN_EXPORTED(Category.MARKETING),
    CAMPAIGN_DELETED(Category.MARKETING),

    ACCOUNT_CREATED(Category.ACCOUNTING), ACCOUNT_UPDATED(Category.ACCOUNTING), BOOKS_STARTED(Category.ACCOUNTING),
    BOOKS_LOCKED(Category.ACCOUNTING), ACCOUNTING_MODE_CHANGED(Category.ACCOUNTING), JOURNAL_POSTED(Category.ACCOUNTING), JOURNAL_REVERSED(Category.ACCOUNTING),
    OTHER_INCOME_RECORDED(Category.ACCOUNTING), OTHER_EXPENSE_RECORDED(Category.ACCOUNTING), OTHER_TRANSACTION_VOIDED(Category.ACCOUNTING);

    public enum Category { AUTH, USERS, SETTINGS, CATALOG, INVENTORY, PURCHASING, SALES, MARKETING, ACCOUNTING }

    private final Category category;

    AuditAction(Category category) {
        this.category = category;
    }

    public Category category() {
        return category;
    }
}
