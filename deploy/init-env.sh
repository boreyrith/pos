#!/bin/sh
# Creates deploy/.env with strong random secrets, asking for the few settings that are yours.
# Run once on the server. It never overwrites an existing .env.
set -eu
cd "$(dirname "$0")"
if [ -f .env ]; then
  # Already set up: carry on (so "./init-env.sh && docker compose ... up" still starts the app).
  echo "deploy/.env already exists, keeping it. Edit it to change settings; the first admin's password is ADMIN_PASSWORD in it."
  exit 0
fi
rand() { openssl rand -base64 "$1" | tr -d '\n'; }
# The first port from $1 up that nothing on this machine listens on (other sites may use 3000, 8081...).
free_port() {
  p=$1
  if command -v ss >/dev/null 2>&1; then
    while ss -ltnH | awk '{print $4}' | grep -Eq "[:.]$p\$"; do p=$((p + 1)); done
  fi
  echo "$p"
}
pw() { openssl rand -hex 24; }

printf 'Address people will open (e.g. pos.myshop.com, 10.0.129.216 or shop-pc.local): '; read -r site
printf 'Separate address for the API, e.g. api.pos.myshop.com (leave empty if not needed): '; read -r apisite
printf 'Does this server already run nginx or Apache on ports 80/443? [y/N]: '; read -r proxied
case "$proxied" in
  [yY]*) proxied=yes; email= ;;
  *) proxied=; printf 'Email for Let'"'"'s Encrypt (leave empty for an internal certificate on a LAN): '; read -r email ;;
esac
printf 'Store name: '; read -r store; store=$(printf '%s' "$store" | tr -d '"')
printf 'First admin username [admin]: '; read -r admin; admin=${admin:-admin}
adminpw=$(openssl rand -base64 12 | tr -d '\n/+=')

umask 077
cat > .env <<ENV
# Generated by init-env.sh on $(date -u +%Y-%m-%d). Keep this file private and backed up:
# losing SECRETS_KEY means re-entering the Bakong token; changing JWT_SECRET signs everyone out.
SITE_ADDRESS=${site}
API_ADDRESS=${apisite}
TLS=${email:-internal}

DB_PASSWORD=$(pw)
DB_ROOT_PASSWORD=$(pw)

JWT_SECRET=$(rand 48)
SECRETS_KEY=$(rand 32)
REFRESH_COOKIE_SECURE=true

STORE_NAME="${store:-POS Store}"
STORE_TIMEZONE=Asia/Phnom_Penh

# Used only on the very first start, to create the first administrator (who must change the password).
ADMIN_USERNAME=${admin}
ADMIN_PASSWORD=${adminpw}

# KHQR starts in test mode; switch to live payments in Settings > Taxes & payments.
KHQR_MODE=SIMULATED

BACKUP_EVERY_HOURS=24
BACKUP_KEEP_DAYS=14
ENV
if [ -n "$proxied" ]; then
  cat >> .env <<'ENV'

# Behind your own nginx/Apache: no Caddy; the web app and API listen on this machine only.
# Site configs: ./proxy-config.sh nginx|apache. Use plain "docker compose ..." (no -f) so both files apply.
COMPOSE_FILE=docker-compose.prod.yml:docker-compose.behind-proxy.yml
ENV
  web_port=$(free_port 3000)
  api_port=$(free_port 8081)
  [ "$api_port" != "$web_port" ] || api_port=$(free_port $((api_port + 1)))
  printf 'WEB_PORT=%s\nAPI_PORT=%s\n' "$web_port" "$api_port" >> .env
fi
echo
echo "Wrote deploy/.env. First sign-in: ${admin} / ${adminpw}  (you'll be asked to choose a new password)"
[ -z "$proxied" ] || echo "Next: docker compose up -d --build, then ./proxy-config.sh nginx (or apache); see DEPLOY.md."
