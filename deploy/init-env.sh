#!/bin/sh
# Creates deploy/.env with strong random secrets, asking for the few settings that are yours.
# Run once on the server. It never overwrites an existing .env.
set -eu
cd "$(dirname "$0")"
if [ -f .env ]; then echo ".env already exists; edit it instead." >&2; exit 1; fi
rand() { openssl rand -base64 "$1" | tr -d '\n'; }
pw() { openssl rand -hex 24; }

printf 'Address people will open (e.g. pos.myshop.com, 10.0.129.216 or shop-pc.local): '; read -r site
printf 'Email for Let'"'"'s Encrypt (leave empty for an internal certificate on a LAN): '; read -r email
printf 'Store name: '; read -r store
printf 'First admin username [admin]: '; read -r admin; admin=${admin:-admin}
adminpw=$(openssl rand -base64 12 | tr -d '\n/+=')

umask 077
cat > .env <<ENV
# Generated by init-env.sh on $(date -u +%Y-%m-%d). Keep this file private and backed up:
# losing SECRETS_KEY means re-entering the Bakong token; changing JWT_SECRET signs everyone out.
SITE_ADDRESS=${site}
TLS=${email:-internal}

DB_PASSWORD=$(pw)
DB_ROOT_PASSWORD=$(pw)

JWT_SECRET=$(rand 48)
SECRETS_KEY=$(rand 32)
REFRESH_COOKIE_SECURE=true

STORE_NAME=${store:-POS Store}
STORE_TIMEZONE=Asia/Phnom_Penh

# Used only on the very first start, to create the first administrator (who must change the password).
ADMIN_USERNAME=${admin}
ADMIN_PASSWORD=${adminpw}

# KHQR starts in test mode; switch to live payments in Settings > Taxes & payments.
KHQR_MODE=SIMULATED

BACKUP_EVERY_HOURS=24
BACKUP_KEEP_DAYS=14
ENV
echo
echo "Wrote deploy/.env. First sign-in: ${admin} / ${adminpw}  (you'll be asked to choose a new password)"
