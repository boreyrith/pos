"""Copies the web app's Khmer (frontend/src/lib/i18n/km.ts and km-patterns.ts) into
lib/core/km_web.g.dart, so the app shows the same wording, and server messages in Khmer.
Run from mobile/: python3 tool/gen_km.py"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
web = root.parent / "frontend/src/lib/i18n"

string = r'"(?:[^"\\]|\\.)*"'
entries = re.findall(rf'^\s*({string}):\s*({string}),?\s*$', (web / "km.ts").read_text(), re.M)
patterns = re.findall(rf'^\s*\[/(.+)/([a-z]*),\s*({string})\],?\s*$', (web / "km-patterns.ts").read_text(), re.M)


def dart(s: str) -> str:
    """A Dart string literal for a Python string."""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


out = [
    "// GENERATED by tool/gen_km.py from frontend/src/lib/i18n. Do not edit.",
    "// ignore_for_file: lines_longer_than_80_chars",
    "",
    "/// Khmer for the web interface and for server messages, keyed by the English text.",
    "const kmWeb = <String, String>{",
]
for k, v in entries:
    out.append(f"  {dart(json.loads(k))}: {dart(json.loads(v))},")
out += ["};", "", "/// Server messages with names and numbers in them; \\$1, \\$2... are the captured parts.",
        "final kmPatterns = <(RegExp, String)>["]
for regex, flags, khmer in patterns:
    regex = regex.replace("\\/", "/")
    ci = ", caseSensitive: false" if "i" in flags else ""
    out.append(f"  (RegExp({dart(regex)}{ci}), {dart(json.loads(khmer))}),")
out.append("];")
(root / "lib/core/km_web.g.dart").write_text("\n".join(out) + "\n")
print(f"{len(entries)} texts, {len(patterns)} patterns")
